//go:build ignore

// changelog_generate 把 changelog 目录的未发布日志编成管理服务的私有常量。
package main

import (
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"
	"unicode/utf8"
)

func main() {
	raw, err := os.ReadFile("../../../changelog/unreleased/en.md")
	if err != nil {
		log.Fatal(err)
	}
	if !utf8.Valid(raw) {
		log.Fatal("changelog/unreleased/en.md: Markdown must contain valid UTF-8")
	}
	source := fmt.Sprintf("// Code generated by go generate; DO NOT EDIT.\n\npackage manage\n\nconst coreChangelogMarkdown = %q\n", "# Changelog\n\n## [Unreleased]\n"+strings.TrimPrefix(string(raw), "# Unreleased"))
	formatted, err := format.Source([]byte(source))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("changelog_core.go", formatted, 0600); err != nil {
		log.Fatal(err)
	}
}
