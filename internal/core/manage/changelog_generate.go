//go:build ignore

// changelog_generate 把 changelog 目录的双语正式日志编入管理服务。
package main

import (
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"strings"
	"unicode/utf8"

	"github.com/AlonaBot/AlonaBot/contracts/manifest"
)

func main() {
	source, err := generate("../../../changelog")
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("changelog_core.go", source, 0600); err != nil {
		log.Fatal(err)
	}
}

func generate(root string) ([]byte, error) {
	versions, err := os.ReadDir(root)
	if err != nil {
		return nil, err
	}
	var source strings.Builder
	source.WriteString("// Code generated by go generate; DO NOT EDIT.\n\npackage manage\n\nvar coreChangelogMarkdown = map[string]string{\n")
	for _, locale := range []struct{ file, tag string }{{"en", "en-US"}, {"zh-CN", "zh-CN"}} {
		var markdown strings.Builder
		for _, version := range versions {
			name := version.Name()
			if !version.IsDir() || !strings.HasPrefix(name, "v") || !manifest.ValidVersion(strings.TrimPrefix(name, "v")) {
				continue
			}
			path := filepath.Join(root, name, locale.file+".md")
			raw, err := os.ReadFile(path)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", path, err)
			}
			if !utf8.Valid(raw) {
				return nil, fmt.Errorf("%s: Markdown must contain valid UTF-8", path)
			}
			if strings.TrimSpace(string(raw)) == "" {
				return nil, fmt.Errorf("%s: Markdown must not be blank", path)
			}
			fmt.Fprintf(&markdown, "## [%s]\n\n%s\n", strings.TrimPrefix(name, "v"), raw)
		}
		fmt.Fprintf(&source, "%q: %q,\n", locale.tag, markdown.String())
	}
	source.WriteString("}\n")
	return format.Source([]byte(source.String()))
}
