//go:build ignore

// changelog_generate 把仓库根目录更新日志编成管理服务的私有常量。
package main

import (
	"fmt"
	"go/format"
	"log"
	"os"
	"unicode/utf8"
)

func main() {
	raw, err := os.ReadFile("../../../CHANGELOG.md")
	if err != nil {
		log.Fatal(err)
	}
	if !utf8.Valid(raw) {
		log.Fatal("CHANGELOG.md: Markdown must contain valid UTF-8")
	}
	source := fmt.Sprintf("// Code generated by go generate; DO NOT EDIT.\n\npackage manage\n\nconst coreChangelogMarkdown = %q\n", string(raw))
	formatted, err := format.Source([]byte(source))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("changelog_core.go", formatted, 0600); err != nil {
		log.Fatal(err)
	}
}
