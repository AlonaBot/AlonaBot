//go:build ignore

// changelog_generate 把 changelog 目录的正式版本日志编成管理服务的私有常量。
package main

import (
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"strings"
	"unicode/utf8"

	"github.com/AlonaBot/AlonaBot/contracts/manifest"
)

func main() {
	const directory = "../../../changelog"
	entries, err := os.ReadDir(directory)
	if err != nil {
		log.Fatal(err)
	}
	var markdown strings.Builder
	markdown.WriteString("# Changelog\n")
	for _, entry := range entries {
		version := strings.TrimPrefix(entry.Name(), "v")
		if !entry.IsDir() || !manifest.ValidVersion(version) {
			continue
		}
		filename := filepath.Join(directory, entry.Name(), "en.md")
		raw, err := os.ReadFile(filename)
		if err != nil {
			log.Fatal(err)
		}
		if !utf8.Valid(raw) {
			log.Fatalf("%s: Markdown must contain valid UTF-8", filename)
		}
		fmt.Fprintf(&markdown, "\n## [%s]\n\n%s\n", version, strings.TrimPrefix(string(raw), "# AlonaBot "+entry.Name()+"\n"))
	}
	source := fmt.Sprintf("// Code generated by go generate; DO NOT EDIT.\n\npackage manage\n\nconst coreChangelogMarkdown = %q\n", markdown.String())
	formatted, err := format.Source([]byte(source))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("changelog_core.go", formatted, 0600); err != nil {
		log.Fatal(err)
	}
}
