package pluginkit

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/AlonaBot/AlonaBot/internal/generate"
)

// CompileApp 扫描库模式 main 的组件依赖，经 main 包的 overlay 编入全部资源并构建可执行文件。
// goFlags 仅供仓库测试传入 Go 构建选项，CLI 不暴露。
func CompileApp(ctx context.Context, options generate.Options, outDir string, goFlags ...string) (executable string, err error) {
	// 1. 由 main 的构建列表定位组件；扫描始终沿用调用方的 module 上下文。
	dir, err := filepath.Abs(options.Dir)
	if err != nil {
		return "", err
	}
	dir, err = filepath.EvalSymlinks(dir)
	if err != nil {
		return "", err
	}
	options.Dir = dir
	targetEnv, err := goCommand(ctx, options.Toolchain, dir, "env", "GOOS", "GOARCH")
	if err != nil {
		return "", err
	}
	target := strings.Fields(string(targetEnv))
	if options.GOOS == "" {
		options.GOOS = target[0]
	}
	if options.GOARCH == "" {
		options.GOARCH = target[1]
	}
	listed, err := targetGoCommand(ctx, options, true, "list", "-deps", "-json", ".")
	if err != nil {
		return "", err
	}
	type listedPackage struct {
		Dir, Name, ImportPath string
		Imports               []string
	}
	var packages []listedPackage
	decoder := json.NewDecoder(bytes.NewReader(listed))
	for {
		var pkg listedPackage
		if err := decoder.Decode(&pkg); err == io.EOF {
			break
		} else if err != nil {
			return "", fmt.Errorf("decode application dependencies: %w", err)
		}
		packages = append(packages, pkg)
	}
	entry := packages[len(packages)-1]
	if entry.Name != "main" || !slices.Contains(entry.Imports, modulePath) {
		return "", errors.New("directory must contain plugin.yaml or a main package importing github.com/AlonaBot/AlonaBot")
	}
	var registrations []string
	for _, pkg := range packages {
		_, err := os.Stat(filepath.Join(pkg.Dir, projectFile))
		if errors.Is(err, os.ErrNotExist) {
			continue
		}
		if err != nil {
			return "", err
		}
		componentOptions := options
		componentOptions.Package = pkg.ImportPath
		result, err := generate.Scan(ctx, componentOptions)
		if err != nil {
			return "", fmt.Errorf("scan component %s: %w", pkg.ImportPath, err)
		}
		if len(result.Diagnostics) != 0 {
			var diagnostics []string
			for _, d := range result.Diagnostics {
				diagnostics = append(diagnostics, d.Pos+": "+d.Message)
			}
			return "", fmt.Errorf("scan component %s:\n%s", pkg.ImportPath, strings.Join(diagnostics, "\n"))
		}
		if len(result.Source) == 0 {
			return "", fmt.Errorf("entry package %q has no component constructor", pkg.ImportPath)
		}
		registrations = append(registrations, string(result.Source[strings.Index(string(result.Source), "func init() "):]))
	}
	// 2. 登记文件只注入作者的 main；模块缓存中的组件源码保持只读。
	if outDir == "" {
		outDir = filepath.Join(dir, "bin")
	}
	outDir, err = filepath.Abs(outDir)
	if err != nil {
		return "", err
	}
	if err := os.MkdirAll(outDir, privateMode); err != nil {
		return "", err
	}
	staging, err := os.MkdirTemp(outDir, ".alonabot-app-*")
	if err != nil {
		return "", err
	}
	defer func() { err = errors.Join(err, os.RemoveAll(staging)) }()
	replacements := make(map[string]string)
	if len(registrations) > 0 {
		source := "// Code generated by alonabot. DO NOT EDIT.\npackage main\nimport genimpl \"github.com/AlonaBot/AlonaBot/sdk/genimpl\"\n" + strings.Join(registrations, "\n")
		path := filepath.Join(staging, registrationFile)
		if err := os.WriteFile(path, []byte(source), fileMode); err != nil {
			return "", err
		}
		replacements[filepath.Join(dir, registrationFile)] = path
	}
	overlay, err := json.Marshal(map[string]any{"Replace": replacements})
	if err != nil {
		return "", err
	}
	overlayPath := filepath.Join(staging, "overlay.json")
	if err := os.WriteFile(overlayPath, overlay, fileMode); err != nil {
		return "", err
	}
	name := filepath.Base(dir)
	if options.GOOS == "windows" {
		name += ".exe"
	}
	executable = filepath.Join(outDir, name)
	// 3. 构建成功后再发布，保留此前可运行的产物。
	temporary := filepath.Join(staging, name)
	args := append([]string{"build", "-buildvcs=false", "-overlay", overlayPath, "-o", temporary}, goFlags...)
	args = append(args, ".")
	if _, err := targetGoCommand(ctx, options, true, args...); err != nil {
		return "", err
	}
	if err := os.Rename(temporary, executable); err != nil {
		return "", fmt.Errorf("publish application executable: %w", err)
	}
	return executable, nil
}
