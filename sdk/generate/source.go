package generate

import (
	"bytes"
	"fmt"
	"go/format"
	"maps"
	"slices"
	"strconv"
)

func (s *scan) source() ([]byte, error) {
	// 1. 所有跨包引用按导入路径分配固定别名。
	imports := map[string]string{sdkPath: ""}
	for _, command := range s.result.Commands {
		if command.Package != s.entry.ImportPath {
			imports[command.Package] = ""
		}
	}
	for _, event := range s.result.Events {
		if event.Package != s.entry.ImportPath {
			imports[event.Package] = ""
		}
	}
	var paths []string
	for path := range imports {
		paths = append(paths, path)
	}
	slices.Sort(paths)
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by alonabot plugin generate. DO NOT EDIT.\n\npackage %s\n\nimport (\n", s.entry.Name)
	for i, path := range paths {
		alias := "alonabotgen" + strconv.Itoa(i)
		imports[path] = alias
		fmt.Fprintf(&out, "%s %q\n", alias, path)
	}
	sdk := imports[sdkPath]
	reference := func(pkg, name string) string {
		if pkg == s.entry.ImportPath {
			return name
		}
		return imports[pkg] + "." + name
	}
	// 2. 嵌入 Schema 与文案原文，并沿描述顺序注册，命令的父 token 通过 Group 逐层表达。
	fmt.Fprintf(&out, ")\n\nfunc init() {\n%s.UseGenerated((*%s)(nil), %s.Generated{\n", sdk, s.roots[0].name, sdk)
	if len(s.result.ConfigSchema) != 0 {
		fmt.Fprintf(&out, "ConfigSchema: []byte(%q),\n", s.result.ConfigSchema)
	}
	if len(s.i18nFiles) != 0 {
		out.WriteString("I18n: map[string][]byte{\n")
		for _, file := range slices.Sorted(maps.Keys(s.i18nFiles)) {
			fmt.Fprintf(&out, "%q: []byte(%q),\n", file, s.i18nFiles[file])
		}
		out.WriteString("},\n")
	}
	if len(s.serviceSchemas) != 0 {
		out.WriteString("ServiceSchemas: map[string][]byte{\n")
		ids := make([]string, 0, len(s.serviceSchemas))
		for id := range s.serviceSchemas {
			ids = append(ids, id)
		}
		slices.Sort(ids)
		for _, id := range ids {
			fmt.Fprintf(&out, "%q: []byte(%q),\n", id, s.serviceSchemas[id])
		}
		out.WriteString("},\n")
	}
	fmt.Fprintf(&out, "Commands: func(r *%s.CommandRegistry) {\n", sdk)
	for _, command := range s.result.Commands {
		out.WriteString("r")
		for _, group := range command.Path[:len(command.Path)-1] {
			fmt.Fprintf(&out, ".Group(%q)", group)
		}
		fmt.Fprintf(&out, ".Command(%q)", command.Path[len(command.Path)-1])
		for _, alias := range command.Aliases {
			out.WriteString(".Alias(")
			for i, value := range alias {
				if i > 0 {
					out.WriteString(", ")
				}
				fmt.Fprintf(&out, "%q", value)
			}
			out.WriteString(")")
		}
		fmt.Fprintf(&out, ".Priority(%d).Handle(%s)\n", command.Priority, reference(command.Package, command.Func))
	}
	fmt.Fprintf(&out, "},\nEvents: func(r *%s.EventRegistry) {\n", sdk)
	for _, event := range s.result.Events {
		fmt.Fprintf(&out, "r.On(%q, %q).Priority(%d).Handle(%s)\n", event.RouteID, event.EventType, event.Priority, reference(event.Package, event.Func))
	}
	out.WriteString("},\n})\n}\n")
	source, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated registration: %w", err)
	}
	return source, nil
}
