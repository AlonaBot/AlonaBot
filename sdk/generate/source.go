package generate

import (
	"bytes"
	"fmt"
	"go/format"
	"slices"
	"strconv"
)

func (s *scan) source() ([]byte, error) {
	// 1. 所有跨包引用按导入路径分配固定别名。
	imports := map[string]string{sdkPath: ""}
	for _, command := range s.result.Commands {
		if command.Package != s.entry.ImportPath {
			imports[command.Package] = ""
		}
	}
	for _, event := range s.result.Events {
		if event.Package != s.entry.ImportPath {
			imports[event.Package] = ""
		}
	}
	var paths []string
	for path := range imports {
		paths = append(paths, path)
	}
	slices.Sort(paths)
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by alonabot plugin generate. DO NOT EDIT.\n\npackage %s\n\nimport (\n", s.entry.Name)
	for i, path := range paths {
		alias := "alonabotgen" + strconv.Itoa(i)
		imports[path] = alias
		fmt.Fprintf(&out, "%s %q\n", alias, path)
	}
	sdk := imports[sdkPath]
	reference := func(pkg, name string) string {
		if pkg == s.entry.ImportPath {
			return name
		}
		return imports[pkg] + "." + name
	}
	// 2. 沿描述顺序注册，命令的父 token 通过 Group 逐层表达。
	fmt.Fprintf(&out, ")\n\nfunc init() {\n%s.UseGenerated((*%s)(nil), %s.Generated{\nCommands: func(r *%s.CommandRegistry) {\n", sdk, s.roots[0].name, sdk, sdk)
	for _, command := range s.result.Commands {
		for _, group := range command.Path[:len(command.Path)-1] {
			fmt.Fprintf(&out, "r.Group(%q, func(r *%s.CommandGroup) {\n", group, sdk)
		}
		fmt.Fprintf(&out, "r.Command(%q, %s", command.Path[len(command.Path)-1], reference(command.Package, command.Func))
		for _, alias := range command.Aliases {
			fmt.Fprintf(&out, ", %s.Alias(", sdk)
			for i, value := range alias {
				if i > 0 {
					out.WriteString(", ")
				}
				fmt.Fprintf(&out, "%q", value)
			}
			out.WriteString(")")
		}
		fmt.Fprintf(&out, ", %s.Priority(%d))\n", sdk, command.Priority)
		for range len(command.Path) - 1 {
			out.WriteString("})\n")
		}
	}
	fmt.Fprintf(&out, "},\nEvents: func(r *%s.EventRegistry) {\n", sdk)
	for _, event := range s.result.Events {
		fmt.Fprintf(&out, "r.On(%q, %q, %s, %s.Priority(%d))\n", event.RouteID, event.EventType, reference(event.Package, event.Func), sdk, event.Priority)
	}
	out.WriteString("},\n})\n}\n")
	source, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated registration: %w", err)
	}
	return source, nil
}
