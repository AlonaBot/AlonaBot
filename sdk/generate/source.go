package generate

import (
	"bytes"
	"fmt"
	"go/format"
	"maps"
	"slices"
)

func (s *scan) source() ([]byte, error) {
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by alonabot plugin generate. DO NOT EDIT.\n\npackage %s\n\nimport alonabotgen0 %q\n\n", s.entry.Name, sdkPath)
	if s.adapterProject {
		fmt.Fprintf(&out, "func init() {\nalonabotgen0.UseGeneratedAdapter((*%s)(nil), alonabotgen0.Generated{", s.adapterRoot.name)
	} else {
		out.WriteString("var alonabotGenerated = alonabotgen0.Generated{")
	}
	if s.projectManifest != nil || s.adapterProject || len(s.result.ConfigSchema) != 0 || len(s.serviceSchemas) != 0 || len(s.i18nFiles) != 0 || len(s.paramNames) != 0 {
		out.WriteByte('\n')
	}

	if s.projectManifest != nil {
		fmt.Fprintf(&out, "Manifest: []byte(%q),\n", s.projectManifest)
	}
	if s.adapterProject {
		fmt.Fprintf(&out, "AdapterConfigSchema: []byte(%q),\n", s.instanceJSON)
	}
	if len(s.result.ConfigSchema) != 0 {
		fmt.Fprintf(&out, "ConfigSchema: []byte(%q),\n", s.result.ConfigSchema)
	}
	if len(s.i18nFiles) != 0 {
		out.WriteString("I18n: map[string][]byte{\n")
		for _, file := range slices.Sorted(maps.Keys(s.i18nFiles)) {
			fmt.Fprintf(&out, "%q: []byte(%q),\n", file, s.i18nFiles[file])
		}
		out.WriteString("},\n")
	}
	if len(s.serviceSchemas) != 0 {
		out.WriteString("ServiceSchemas: map[string][]byte{\n")
		ids := make([]string, 0, len(s.serviceSchemas))
		for id := range s.serviceSchemas {
			ids = append(ids, id)
		}
		slices.Sort(ids)
		for _, id := range ids {
			fmt.Fprintf(&out, "%q: []byte(%q),\n", id, s.serviceSchemas[id])
		}
		out.WriteString("},\n")
	}
	if len(s.paramNames) != 0 {
		out.WriteString("ParamNames: map[string][]string{\n")
		for _, key := range slices.Sorted(maps.Keys(s.paramNames)) {
			fmt.Fprintf(&out, "%q: {", key)
			for _, name := range s.paramNames[key] {
				fmt.Fprintf(&out, "%q,", name)
			}
			out.WriteString("},\n")
		}
		out.WriteString("},\n")
	}
	if s.adapterProject {
		out.WriteString("})\n}\n")
	} else {
		out.WriteString("}\n")
	}
	source, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated registration: %w", err)
	}
	return source, nil
}
